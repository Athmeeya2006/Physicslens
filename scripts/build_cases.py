"""The real-world cases, one card each, built from the result files (never hand-set).

  python scripts/build_cases.py            # writes frontend/public/cases.json and the README table
  python scripts/build_cases.py --check    # fails if the README table is not what the results say

Each card: the problem, who has it, what PhysicsLens gives them, one number against an independent truth, the status
(from the result file, by the rule written next to the case), what it cannot do, and a link. A case whose result
file does not exist yet is "not yet validated", with no number. Everything is read from committed files (the
sim-to-real comparison is recomputed from the gallery result), so CI can check the README table. Local and free.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from physicslens.export.outcome import build_outcome

README = ROOT / "README.md"
OUT = ROOT / "frontend" / "public" / "cases.json"
START, END = "<!-- cases:start (generated by scripts/build_cases.py) -->", "<!-- cases:end -->"
SITE = "https://physicslens.vercel.app"


def _json(rel: str) -> dict[str, Any] | None:
    p = ROOT / rel
    return json.loads(p.read_text()) if p.is_file() else None


def _gallery_outcome(name: str) -> dict[str, Any] | None:
    result = _json(f"gallery/gallery-{name}/result.json")
    meta = _json(f"gallery/gallery-{name}/meta.json") or {}
    return build_outcome(result, truth=meta.get("truth")) if result else None


def lab() -> dict[str, Any]:
    o = _gallery_outcome("pendulum")
    c = (o or {}).get("checked_against")
    return {"id": "lab", "title": "Lab measurement", "problem": "Measuring a physical constant needs a lab setup and someone to fit the data.",
            "who": "students, teachers, anyone checking an experiment",
            "gives": "the constant with a 95% interval, the law it follows, and the recording that would settle what is still open",
            "number": f"g = {c['measured']:.3f} m/s² against {c['truth']} ({abs(c['relative_error']):.2%} off)" if c else None,
            "status": (o or {}).get("status", "not yet validated"),
            "status_rule": "the result's own outcome card: proven when the truth lies inside its interval",
            "cant": "it needs a known length (or another scale) in the picture; the arc alone cannot fix the length when the pivot is out of view",
            "link": "/?run=gallery-pendulum"}


def sim_to_real() -> dict[str, Any]:
    from physicslens.export.sim2real import compare_to_video, measured_coordinates

    r = _json("gallery/gallery-spring/result.json")
    v = None
    if r and r.get("fit_state"):
        calibrated = (r.get("calibration") or {}).get("source", "none") != "none"
        v = compare_to_video(measured_coordinates(r), r["fit_state"], calibrated)  # deterministic, under a second
    ratio = v["ratio_heldout"] if v else None
    return {"id": "robotics", "title": "Robotics: sim-to-real", "problem": "Simulators use textbook physics, so a controller tuned in simulation fails on the real machine.",
            "who": "robotics engineers",
            "gives": "a calibrated model with intervals, exported to MuJoCo, URDF and SDF, checked by replaying it in MuJoCo",
            "number": (f"on motion it never saw, the calibrated spring lands {ratio:.1f} times closer to the real track than the "
                       "textbook spring") if v else None,
            "status": "not yet validated" if v is None else "proven" if ratio > 1 else "partial",
            "status_rule": "proven when the calibrated model forecasts the real video's held-out quarter better than the textbook model",
            "cant": "one rigid body at a time, filmed side-on; the control comparison runs in simulation only",
            "link": "/?run=gallery-spring"}


def health() -> dict[str, Any]:
    r = _json("data/health/results.json")
    return {"id": "health", "title": "Machine health", "problem": "Wear changes a machine's damping and frequency long before it fails.",
            "who": "maintenance engineers",
            "gives": "drift alerts when two recordings of the same machine disagree beyond their intervals",
            "number": r.get("number") if r else None, "status": (r or {}).get("status", "not yet validated"),
            "status_rule": "needs recordings of a machine whose wear is known independently",
            "cant": "no validation on a real machine with known wear yet: the drift test is checked on simulated recordings only",
            "link": "/health"}


def audit() -> dict[str, Any]:
    a = _json("frontend/public/audit_study.json")
    real = next((x for x in (a or {}).get("sources", []) if x["key"] == "real"), None)
    gen = (a or {}).get("analysis", {}).get("sets", {}).get("generated", {}).get("flagged_among_judged")
    number = (f"real footage: {real['flagged']} of {real['judged']} judged clips flagged; AI-generated: {gen['k']} of {gen['n']}"
              if real and gen else None)
    proven = bool(real and real["judged"] >= 30 and real["flagged"] == 0)
    return {"id": "audit", "title": "Physics audit of video", "problem": "Generated video often breaks physics, and nobody measures how often.",
            "who": "video-model builders and anyone checking footage",
            "gives": "a verdict per clip (consistent, violates physics, or cannot judge) with the measured reason",
            "number": number, "status": "not yet validated" if not real else "proven" if proven else "partial",
            "status_rule": "proven when at least 30 real clips are judged and none is wrongly flagged",
            "cant": "most clips cannot be judged (no clean single object or too short); a clean audit is not proof a clip is real",
            "link": "/audit"}


def timing() -> dict[str, Any]:
    t = _json("data/astro/timing/results.json")
    w = (t or {}).get("wasp12b")
    o = (w or {}).get("outcome") or {}
    c = o.get("checked_against")
    k = ((t or {}).get("kepler88b") or {}).get("outcome") or {}
    return {"id": "timing", "title": "Exoplanet transit timing", "problem": "Predicted transit times go stale, wasting telescope time; a transit's timing can hide a planet.",
            "who": "observatories, amateur transit-timing networks, exoplanet researchers",
            "gives": "refreshed transit windows (calendar and CSV), a list of stale ephemerides, and the law behind the timings",
            "number": (f"WASP-12b's orbit shrinks by {abs(c['measured']):.1f} ms/yr against the published {abs(c['truth']):.0f} ± 2; "
                       f"Kepler-88's unseen planet: {k.get('status', 'not run')}") if c else None,
            "status": o.get("status", "not yet validated"),
            "status_rule": "WASP-12b's outcome card: proven when the published rate lies inside the measured interval",
            "cant": "timing inversions are degenerate (mass against eccentricity); the Kepler-88 fit forecasts to 15 min, not the 3 min its data allow",
            "link": "/timing"}


def fireball() -> dict[str, Any]:
    f = _json("data/astro/fireball/results.json")
    o = (f or {}).get("outcome") or {}
    s = (f or {}).get("summary")
    return {"id": "fireball", "title": "Fireballs and meteorite falls", "problem": "Fresh meteorites are valuable, and finding them depends on a good search map.",
            "who": "fireball networks, meteorite hunters",
            "gives": "whether anything survived, the orbit it came from, and a strewn-field map (GeoJSON, KML)",
            "number": (f"Winchcombe: within {s['max_across_m']:.0f} m of all {s['finds']} recovered stones across the track, "
                       f"{s['along_either']} of {s['finds']} along it") if s else None,
            "status": o.get("status", "not yet validated"),
            "status_rule": "proven when the orbit matches within 2 sigma, the main mass is reproduced and every find is",
            "cant": "it starts from a triangulated trajectory, not one video; masses carry a factor-of-two uncertainty from shape and density",
            "link": "/fireball"}


def pending(id_: str, title: str, problem: str, who: str, gives: str, rel: str, cant: str, link: str | None) -> dict[str, Any]:
    r = _json(rel)
    o = (r or {}).get("outcome") or {}
    c = o.get("checked_against")
    return {"id": id_, "title": title, "problem": problem, "who": who, "gives": gives,
            "number": f"{c['name']}: {c['measured']:.4g} against {c['truth']:.4g}" if c else None,
            "status": o.get("status", "not yet validated"), "status_rule": "the case's own outcome card",
            "cant": cant, "link": link if r else None}


def cases() -> list[dict[str, Any]]:
    return [
        sim_to_real(), lab(), timing(), fireball(), audit(), health(),
        pending("satellites", "Satellites", "A satellite that moved, decays or tumbles is not where the catalogue says.",
                "amateur trackers, space-safety analysts", "manoeuvre and tumble detection against the orbital catalogue",
                "data/astro/satellites/results.json", "needs frame times accurate to a few milliseconds (a GPS-synced clock)", "/satellites"),
        pending("asteroids", "Asteroids and occultations", "Asteroid orbits and shapes need many careful observations.",
                "amateur astronomers, occultation observers", "a submittable report, and an asteroid's outline from star disappearances",
                "data/astro/asteroids/results.json", "the core astrometry is already done well by free tools", "/asteroids"),
        pending("sun", "The Sun's rotation", "When will this sunspot region face the Earth again?",
                "space-weather watchers, students", "the differential rotation law and return dates for active regions",
                "data/astro/sun/results.json", "forecasting region returns is already done operationally by NOAA", "/sun"),
    ]


def table(rows: list[dict[str, Any]]) -> str:
    lines = [START, "", "| Case | Who has the problem | What PhysicsLens gives them | Against an independent truth | Status | What it can't do |",
             "|---|---|---|---|---|---|"]
    for c in rows:
        name = f"[{c['title']}]({SITE}{c['link']})" if c["link"] else c["title"]
        lines.append(f"| {name} | {c['who']} | {c['gives']} | {c['number'] or 'no result yet'} | {c['status']} | {c['cant']} |")
    return "\n".join([*lines, "", END])


def main() -> None:
    rows = cases()
    want = table(rows)
    text = README.read_text()
    if START not in text or END not in text:
        sys.exit("README.md has no cases table markers.")
    i, j = text.index(START), text.index(END) + len(END)
    if "--check" in sys.argv:
        if text[i:j] != want:
            sys.exit("The README cases table differs from the results: run python scripts/build_cases.py")
        print("README cases table matches the results.")
        return
    OUT.write_text(json.dumps({"generated": "scripts/build_cases.py", "cases": rows}, indent=1))
    README.write_text(text[:i] + want + text[j:])
    print(f"{len(rows)} cases: " + ", ".join(f"{c['id']} {c['status']}" for c in rows))


if __name__ == "__main__":
    main()
