def cases() -> list[dict[str, Any]]:
    return [sim_to_real(), lab(), timing(), fireball(), sun(), occultation(), asteroids(), satellites(), audit(), health()]


def table(rows: list[dict[str, Any]]) -> str:
    lines = [START, "", "| Case | Who has the problem | What PhysicsLens gives them | Against an independent truth | Status | What it can't do |",
             "|---|---|---|---|---|---|"]
    for c in rows:
        name = f"[{c['title']}]({SITE}{c['link']})" if c["link"] else c["title"]
        lines.append(f"| {name} | {c['who']} | {c['gives']} | {c['number'] or 'no result yet'} | {c['status']} | {c['cant']} |")
    return "\n".join([*lines, "", END])


def main() -> None:
    rows = cases()
    want = table(rows)
    text = README.read_text()
    if START not in text or END not in text:
        sys.exit("README.md has no cases table markers.")
    i, j = text.index(START), text.index(END) + len(END)
    if "--check" in sys.argv:
        if text[i:j] != want:
            sys.exit("The README cases table differs from the results: run python scripts/build_cases.py")
        print("README cases table matches the results.")
        return
    OUT.write_text(json.dumps({"generated": "scripts/build_cases.py", "cases": rows}, indent=1))
    README.write_text(text[:i] + want + text[j:])
    print(f"{len(rows)} cases: " + ", ".join(f"{c['id']} {c['status']}" for c in rows))


if __name__ == "__main__":
    main()
