"""The real-world cases, one card each, built from the result files (never hand-set).

  python scripts/build_cases.py            # writes frontend/public/cases.json and the README table
  python scripts/build_cases.py --check    # fails if the README table is not what the results say

Each card: the problem, who has it, what PhysicsLens gives them, one number against an independent truth, the status
(from the result file, by the rule written next to the case), what it cannot do, and a link. A case whose result
file does not exist yet is "not yet validated", with no number. Everything is read from committed files (the
sim-to-real comparison is recomputed from the gallery result), so CI can check the README table. Local and free.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from physicslens.export.outcome import build_outcome

README = ROOT / "README.md"
OUT = ROOT / "frontend" / "public" / "cases.json"
START, END = "<!-- cases:start (generated by scripts/build_cases.py) -->", "<!-- cases:end -->"
SITE = "https://physicslens.vercel.app"


def _json(rel: str) -> dict[str, Any] | None:
    p = ROOT / rel
    return json.loads(p.read_text()) if p.is_file() else None


def _gallery_outcome(name: str) -> dict[str, Any] | None:
    result = _json(f"gallery/gallery-{name}/result.json")
    meta = _json(f"gallery/gallery-{name}/meta.json") or {}
    return build_outcome(result, truth=meta.get("truth")) if result else None


def lab() -> dict[str, Any]:
    o = _gallery_outcome("pendulum")
    c = (o or {}).get("checked_against")
    return {"id": "lab", "title": "Lab measurement", "problem": "Measuring a physical constant needs a lab setup and someone to fit the data.",
            "who": "students, teachers, anyone checking an experiment",
            "gives": "the constant with a 95% interval, the law it follows, and the recording that would settle what is still open",
            "number": f"g = {c['measured']:.3f} m/s² against {c['truth']} ({abs(c['relative_error']):.2%} off)" if c else None,
            "status": (o or {}).get("status", "not yet validated"),
            "status_rule": "the result's own outcome card: proven when the truth lies inside its interval",
            "cant": "it needs a known length (or another scale) in the picture; the arc alone cannot fix the length when the pivot is out of view",
            "link": "/?run=gallery-pendulum"}


def sim_to_real() -> dict[str, Any]:
    from physicslens.export.sim2real import compare_to_video, measured_coordinates

    r = _json("gallery/gallery-paperbag/result.json")
    v = None
    if r and r.get("fit_state"):
        calibrated = (r.get("calibration") or {}).get("source", "none") != "none"
        v = compare_to_video(measured_coordinates(r), r["fit_state"], calibrated)  # deterministic, under a second
    ratio = v["ratio_heldout"] if v else None
    # A stronger baseline than drag-free: the drag law an engineer would reach for, fitted to the same training window
    # by the same verification (its held-out error against the accepted law's).
    rank = {f["model_id"]: f for f in (r or {}).get("ranking", [])}
    acc = (r or {}).get("fit_state", {}).get("model_id")
    quad = (rank["quadratic_drag"]["heldout_nrmse"] / rank[acc]["heldout_nrmse"]
            if acc in rank and "quadratic_drag" in rank and acc != "quadratic_drag" else None)
    return {"id": "robotics", "title": "Robotics: sim-to-real", "problem": "Simulators use textbook physics, so a controller tuned in simulation fails on the real machine.",
            "who": "robotics engineers",
            "gives": "a calibrated model with intervals, exported to MuJoCo, URDF and SDF, checked by replaying it in MuJoCo",
            "number": (f"on flight it never saw, the calibrated model of a thrown paper bag lands {ratio:.1f} times closer to the "
                       "real track than the textbook (drag-free) one"
                       + (f", and {quad:.1f} times closer than the standard air-drag law (quadratic, its coefficient fitted to "
                          "the same flight)" if quad else "")) if v else None,
            "status": "not yet validated" if v is None else "proven" if ratio > 1 else "partial",
            "status_rule": "proven when the calibrated model forecasts the real video's held-out quarter better than the textbook model",
            "cant": "one rigid body at a time, filmed side-on; the control comparison runs in simulation only",
            "link": "/?run=gallery-paperbag"}


