def audit() -> dict[str, Any]:
    a = _json("frontend/public/audit_study.json")
    real = next((x for x in (a or {}).get("sources", []) if x["key"] == "real"), None)
    gen = (a or {}).get("analysis", {}).get("sets", {}).get("generated", {}).get("flagged_among_judged")
    number = (f"real footage: {real['flagged']} of {real['judged']} judged clips flagged; AI-generated: {gen['k']} of {gen['n']}"
              if real and gen else None)
    proven = bool(real and real["judged"] >= 30 and real["flagged"] == 0)
    return {"id": "audit", "title": "Physics audit of video", "problem": "Generated video often breaks physics, and nobody measures how often.",
            "who": "video-model builders and anyone checking footage",
            "gives": "a verdict per clip (consistent, violates physics, or cannot judge) with the measured reason",
            "number": number, "status": "not yet validated" if not real else "proven" if proven else "partial",
            "status_rule": "proven when at least 30 real clips are judged and none is wrongly flagged",
            "cant": "most clips cannot be judged (no clean single object or too short); a clean audit is not proof a clip is real",
            "link": "/audit"}


