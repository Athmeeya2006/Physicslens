"""The table for the model-alone baseline: what the reasoning model says from the frames alone, against the truth and
PhysicsLens's verified value.

  python scripts/llm_alone_table.py      # reads benchmark/llm_alone/*.json, writes benchmark/llm_alone/LLM_ALONE.md

The answers themselves come from scripts/llm_alone.py (paid model calls, run once with approval); this step is free.
A model names its parameters freely, so each row says which of its parameters was read as the compared quantity.
"""

from __future__ import annotations

import json
import re
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
from physicslens.physics.gravity import AACHEN, local_g

DIR = ROOT / "benchmark" / "llm_alone"

# The quantity compared per clip: PhysicsLens's parameter, and how to recognise the model's own name for it.
# The Sun's GM shows up as "mu", "GM_sun", "mu = G*M_sun" or "gravitational parameter mu"; "k = sqrt(mu)" (the Gaussian
# constant) also contains "mu" but is a different number, so a name starting with "k" never counts.
GM = r"^(?!k\b)(.*\bmu\b|.*gm|.*g\*m|μ)"
# A truth worked out after the run was recorded: the pendulum's is local gravity at the filming site, not 9.81.
LOCAL_TRUTH = {"gallery-pendulum": {"g": round(local_g(AACHEN), 4)}}
COMPARE = {
    "gallery-pendulum": ("g", r"^g$|grav"),
    "gallery-apophis": ("mu", GM),
    "gallery-jupiter": ("mu", GM),
    "gallery-spring": ("omega", r"omega|angular"),
    "orbit-mercury": ("mu", GM),
    "orbit-mars": ("mu", GM),
    "orbit-ceres": ("mu", GM),
    "orbit-encke": ("mu", GM),
    "gallery-paperbag": ("k", r"^k$|drag|^b$|gamma|damping"),
}


def model_value(answer: dict, pattern: str) -> tuple[float | None, str | None]:
    for p in answer.get("parameters", []):
        if re.search(pattern, p["name"].strip().lower()):
            return float(p["value"]), f"{p['name']} [{p.get('unit', '')}]"
    return None, None


def fmt(v: float | None) -> str:
    return "n/a" if v is None else f"{v:.4g}"


def main() -> None:
    rows = ["| Clip | Quantity | Truth | Model alone: median (range) over attempts | PhysicsLens (verified) | Closer to the truth |",
            "|---|---|---|---|---|---|"]
    notes = []
    for path in sorted(p for p in DIR.glob("*.json") if p.stem in COMPARE):
        rec = json.loads(path.read_text())
        gid = path.stem
        name, pattern = COMPARE[gid]
        values, labels = [], set()
        for a in rec["llm_alone"]:
            v, label = model_value(a["answer"], pattern)
            if v is not None:
                values.append(v)
                labels.add(label)
        truth = LOCAL_TRUTH.get(gid, {}).get(name, rec["truth"].get(name))
        # The verified value from the gallery result as it stands now (the values every tied law agrees on, for a tie).
        # (An orbit video outside the gallery: the PhysicsLens values saved with the answers.)
        gal = DIR.parents[1] / "gallery" / gid / "result.json"
        res = json.loads(gal.read_text()) if gal.is_file() else (rec.get("physicslens") or {})
        pl = next((p for p in res.get("parameters") or res.get("agreed_parameters") or [] if p["name"] == name), None)
        med = statistics.median(values) if values else None
        llm_cell = (f"{fmt(med)} ({fmt(min(values))} to {fmt(max(values))}), {len(values)} of {len(rec['llm_alone'])} "
                    "answers gave one") if values else f"none of {len(rec['llm_alone'])} answers gave one"
        pl_cell = f"{pl['value']:.5g} ± {pl['std']:.2g}" if pl else "n/a"
        if truth is not None and med is not None and pl:
            closer = "PhysicsLens" if abs(pl["value"] - truth) < abs(med - truth) else "model alone"
            err = f" ({abs(med / truth - 1):.1%} vs {abs(pl['value'] / truth - 1):.2%} off)"
        else:
            closer, err = "no independent truth" if truth is None else "n/a", ""
        rows.append(f"| {gid.removeprefix('gallery-').removeprefix('orbit-')} | {name} | {fmt(truth)} | {llm_cell} | {pl_cell} | {closer}{err} |")
        if labels:
            same = len(values) > 1 and len(set(values)) == 1
            notes.append(f"- {gid.removeprefix('gallery-').removeprefix('orbit-')}: read from the model's " + ", ".join(sorted(labels)) + "."
                         + (" The same value in every attempt: a constant recalled from training, not a measurement of"
                            " this clip." if same else ""))
    model = next(iter({a["model"] for p in DIR.glob("*.json") if p.stem in COMPARE for a in json.loads(p.read_text())["llm_alone"]} - {None}), "")
    text = "\n".join([
        "# The reasoning model alone, from the same frames", "",
        (f"Generated by `scripts/llm_alone_table.py` from the answers in this folder ({model}, low reasoning effort, "
         "five fresh attempts per clip, the same keyframes and setup facts PhysicsLens had: lengths, scale, time per "
         "frame). Every raw answer, with its reasoning, is in the JSON files."), "", *rows, "",
        "Which parameter was read:", "",
        *notes, ""])
    (DIR / "LLM_ALONE.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
